export const getDailyWelcomeMessage = (dateKey: string) => {
  let hash = 0;
  for (let i = 0; i < dateKey.length; i += 1) {
    hash = ((hash << 5) - hash) + dateKey.charCodeAt(i);
    hash |= 0;
  }
  return DAILY_WELCOME_MESSAGES[Math.abs(hash) % DAILY_WELCOME_MESSAGES.length];
};
